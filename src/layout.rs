//! std140 / std430 layout helpers for UBO/SSBO interop.
//!
//! GPU buffer blocks follow strict alignment rules that differ from Rust's. The
//! infamous one: a 3-component vector has a base alignment of 16 (not 12), in
//! BOTH std140 and std430. Get this wrong and every field past the first `vec3` is
//! silently misaligned against the shader.
//!
//! This module gives you three things:
//!
//! 1. **Derive macros** — `#[derive(Std140)]` / `#[derive(Std430)]` (with the
//!    `derive` feature, on by default). Declare the block with plain `float3`,
//!    `float4x4`, `[f32; N]` fields exactly as the shader does; the derive emits a
//!    `NameStd140` struct with explicit padding at the exact GLSL offsets
//!    (including the `vec3 + float` tuck-in), `as_std140()` / `into_inner()`
//!    conversions, `as_bytes()` for the upload, and compile-time offset checks.
//!    See [`Std140Layout`] for the trait every field type must implement.
//!
//! 2. **Alignment rules as constants** — [`Std140Layout::ALIGN`] /
//!    [`Std430Layout::ALIGN`] (or [`std140_align::<T>()`](std140_align)), for
//!    checking a hand-written `#[repr(C, align(16))]` struct.
//!
//! 3. **Wrapper types** — [`Std140<T>`] / [`Std430<T>`] and [`Std140Array`] /
//!    [`Std430Array`] — that resolve to a type carrying the right alignment with
//!    explicit zero padding (`float3` -> [`Padded16<float3, 4>`](Padded16),
//!    `float3x3` -> three padded columns). Use them in hand-written `#[repr(C)]`
//!    structs; each wrapped member gets its own slot, so there is no tuck-in.
//!
//! Rules encoded (base alignment):
//!
//! | type                           | alignment                                   |
//! |--------------------------------|---------------------------------------------|
//! | scalar (`f32`/`i32`/`u32`)     | 4 (`f64`: 8)                                |
//! | vec2                           | 2 * sizeof(component)                       |
//! | vec3, vec4                     | 4 * sizeof(component)                       |
//! | matrix                         | array of columns; each column is a vecR     |
//! | array element / matrix column  | std140 rounds the slot up to 16; std430 keeps the natural alignment |
//! | struct                         | max member alignment; std140 rounds it up to 16 |
//!
//! `bool` is intentionally unsupported — GLSL `bool` is 4 bytes, Rust's is 1. Use
//! `u32` for GPU-facing booleans.

// The layout traits are `unsafe trait`s: the keyword marks the "fully initialised
// plain data" contract that the derived `as_bytes()` relies on. There are no
// unsafe *operations* in this module.
#![allow(unsafe_code)]

use core::fmt::Debug;

use crate::matrix::Matrix;
use crate::scalar::{Scalar, Vector};
use crate::vector::{Vector2, Vector3, Vector4};

// ---- padded storage -----------------------------------------------------------

/// A storage type holding a `T` at some (larger) alignment and/or size.
/// Implemented by the [`Padded8`]/[`Padded16`]/[`Padded32`] wrappers,
/// [`PaddedCols`], arrays of padded elements, the structs generated by
/// `#[derive(Std140)]`, and — trivially — scalars and vectors themselves.
pub trait Padded<T>: Copy + Debug {
    /// Store `value`, zeroing any padding.
    fn wrap(value: T) -> Self;
    /// The all-zero value (every byte zero, padding included).
    fn zeroed() -> Self;
    /// The wrapped value.
    fn into_inner(self) -> T;
    /// Replace the wrapped value.
    #[inline]
    fn set(&mut self, value: T) {
        *self = Self::wrap(value);
    }
}

macro_rules! padded_identity {
    ($($t:ty),*) => {$(
        impl Padded<$t> for $t {
            #[inline]
            fn wrap(value: $t) -> Self { value }
            #[inline]
            fn zeroed() -> Self { <$t as Scalar>::ZERO }
            #[inline]
            fn into_inner(self) -> $t { self }
        }
    )*};
}
padded_identity!(f32, f64, i32, u32);

impl<V: Vector> Padded<V> for V {
    #[inline]
    fn wrap(value: V) -> Self {
        value
    }
    #[inline]
    fn zeroed() -> Self {
        V::ZERO
    }
    #[inline]
    fn into_inner(self) -> V {
        self
    }
}

impl<T, S: Padded<T>, const N: usize> Padded<[T; N]> for [S; N] {
    #[inline]
    fn wrap(value: [T; N]) -> Self {
        value.map(S::wrap)
    }
    #[inline]
    fn zeroed() -> Self {
        [S::zeroed(); N]
    }
    #[inline]
    fn into_inner(self) -> [T; N] {
        self.map(S::into_inner)
    }
}

macro_rules! padded_wrapper {
    ($(#[$doc:meta] $name:ident = $n:literal;)*) => {$(
        #[$doc]
        ///
        /// `PAD` explicit zero bytes follow the value so the struct has no
        /// uninitialised padding — the whole thing can be viewed as bytes.
        #[repr(C, align($n))]
        #[derive(Clone, Copy, PartialEq)]
        pub struct $name<T, const PAD: usize> {
            /// The stored value.
            pub value: T,
            _pad: [u8; PAD],
        }

        impl<T: Debug, const PAD: usize> Debug for $name<T, PAD> {
            /// Transparent: prints the value, not the padding.
            fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
                self.value.fmt(f)
            }
        }

        impl<T, const PAD: usize> $name<T, PAD> {
            /// Store `value` followed by `PAD` zero bytes.
            #[inline]
            pub const fn new(value: T) -> Self {
                Self { value, _pad: [0; PAD] }
            }
        }
        impl<T, const PAD: usize> From<T> for $name<T, PAD> {
            #[inline]
            fn from(value: T) -> Self { Self::new(value) }
        }
        impl<T: Padded<T>, const PAD: usize> Padded<T> for $name<T, PAD> {
            #[inline]
            fn wrap(value: T) -> Self { Self::new(value) }
            #[inline]
            fn zeroed() -> Self { Self::new(T::zeroed()) }
            #[inline]
            fn into_inner(self) -> T { self.value }
        }
        impl<T: Padded<T>, const PAD: usize> Default for $name<T, PAD> {
            #[inline]
            fn default() -> Self { Self::zeroed() }
        }
    )*};
}
padded_wrapper! {
    /// `T` stored at 8-byte alignment.
    Padded8 = 8;
    /// `T` stored at 16-byte alignment.
    Padded16 = 16;
    /// `T` stored at 32-byte alignment.
    Padded32 = 32;
}

/// A matrix stored as `C` padded columns of type `S` (a [`Padded`] column vector).
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct PaddedCols<S, const C: usize> {
    /// The padded columns.
    pub cols: [S; C],
}

impl<S: Copy + Default, const C: usize> Default for PaddedCols<S, C> {
    #[inline]
    fn default() -> Self {
        Self {
            cols: [S::default(); C],
        }
    }
}
impl<V: Vector, S: Padded<V>, const C: usize> From<Matrix<V, C>> for PaddedCols<S, C> {
    #[inline]
    fn from(m: Matrix<V, C>) -> Self {
        Self::wrap(m)
    }
}
impl<V: Vector, S: Padded<V>, const C: usize> Padded<Matrix<V, C>> for PaddedCols<S, C> {
    #[inline]
    fn wrap(m: Matrix<V, C>) -> Self {
        Self {
            cols: m.cols.map(S::wrap),
        }
    }
    #[inline]
    fn zeroed() -> Self {
        Self {
            cols: [S::zeroed(); C],
        }
    }
    #[inline]
    fn into_inner(self) -> Matrix<V, C> {
        Matrix::from_cols(self.cols.map(S::into_inner))
    }
}

// ---- layout traits ------------------------------------------------------------

/// std140 rules for a type: its base alignment and the storage types that carry it.
///
/// Implemented for `f32`/`i32`/`u32`/`f64`, their `Vector2/3/4`, every matrix and
/// array built from those, and any struct with `#[derive(Std140)]`.
///
/// # Safety
///
/// `Padded`, `Slot` and `Field` must be plain data with every byte initialised:
/// no uninitialised padding, no pointers, no `bool`. The structs generated by the
/// derive macro rely on this to expose themselves as `&[u8]` for uploading.
pub unsafe trait Std140Layout: Copy {
    /// Base alignment of a lone member.
    const ALIGN: usize;
    /// Alignment of an array element (or matrix column): `ALIGN` rounded up to 16.
    /// Not 16 flat — `double3`/`double4` elements need 32.
    const SLOT_ALIGN: usize = if Self::ALIGN < 16 { 16 } else { Self::ALIGN };
    /// Storage for a lone member in a hand-written `#[repr(C)]` struct: carries the
    /// alignment itself (so `Std140<float3>` is 16 bytes at 16).
    type Padded: Padded<Self>;
    /// Storage for an array element (slot rounded up to 16).
    type Slot: Padded<Self>;
    /// Storage for a field of a `#[derive(Std140)]` struct, where the derive
    /// computes the padding: the natural type for scalars and vectors (`float3` is
    /// 12 bytes, so a following `f32` tucks in), padded columns for matrices.
    type Field: Padded<Self>;
}

/// std430 rules for a type: its base alignment and the storage types that carry it.
/// Array elements keep the natural alignment, so there is no separate slot type.
///
/// # Safety
///
/// Same contract as [`Std140Layout`]: `Padded` and `Field` are fully initialised
/// plain data.
pub unsafe trait Std430Layout: Copy {
    /// Base alignment of a lone member (also the array stride alignment).
    const ALIGN: usize;
    /// Storage for a member or array element in a hand-written struct.
    type Padded: Padded<Self>;
    /// Storage for a field of a `#[derive(Std430)]` struct.
    type Field: Padded<Self>;
}

/// `T` stored with std140 alignment. `Std140<float3>` is 16 bytes; `Std140<f32>` is
/// just `f32`; `Std140<MyStruct>` is the `MyStructStd140` the derive generated.
pub type Std140<T> = <T as Std140Layout>::Padded;
/// `T` stored as a std140 array element (slot rounded up to 16 bytes).
pub type Std140Slot<T> = <T as Std140Layout>::Slot;
/// `[T; N]` with std140 array stride: every element slot is rounded up to 16.
pub type Std140Array<T, const N: usize> = [<T as Std140Layout>::Slot; N];
/// `T` stored with std430 alignment.
pub type Std430<T> = <T as Std430Layout>::Padded;
/// `[T; N]` with std430 array stride (natural element alignment).
pub type Std430Array<T, const N: usize> = [<T as Std430Layout>::Padded; N];

/// std140 base alignment of `T`.
#[inline]
pub const fn std140_align<T: Std140Layout>() -> usize {
    T::ALIGN
}
/// std140 array-element (and matrix-column) slot alignment of `T`.
#[inline]
pub const fn std140_slot_align<T: Std140Layout>() -> usize {
    T::SLOT_ALIGN
}
/// std430 base alignment of `T`.
#[inline]
pub const fn std430_align<T: Std430Layout>() -> usize {
    T::ALIGN
}

/// std140 alignment of a struct whose most-aligned member has `max_member_align`:
/// rounded up to 16.
#[inline]
pub const fn std140_struct_align(max_member_align: usize) -> usize {
    if max_member_align < 16 {
        16
    } else {
        max_member_align
    }
}

/// `offset` rounded up to the next multiple of `align` (a power of two).
#[inline]
pub const fn align_up(offset: usize, align: usize) -> usize {
    (offset + align - 1) & !(align - 1)
}

/// The larger of two sizes (const-friendly `max`, used by the derive macros).
#[inline]
pub const fn max_usize(a: usize, b: usize) -> usize {
    if a > b { a } else { b }
}

// ---- scalars and vectors ------------------------------------------------------

macro_rules! layout_impl {
    ($t:ty => $align:literal, padded: $padded:ty, slot: $slot:ty) => {
        // SAFETY: the storage types are repr(C) plain data with explicit padding.
        unsafe impl Std140Layout for $t {
            const ALIGN: usize = $align;
            type Padded = $padded;
            type Slot = $slot;
            type Field = $t;
        }
        // SAFETY: as above.
        unsafe impl Std430Layout for $t {
            const ALIGN: usize = $align;
            type Padded = $padded;
            type Field = $t;
        }
        const _: () = {
            use core::mem::{align_of, size_of};
            // The wrappers must land exactly on the rule — no implicit padding.
            assert!(align_of::<$padded>() == $align);
            assert!(size_of::<$padded>() == align_up(size_of::<$t>(), $align));
            assert!(align_of::<$slot>() == <$t as Std140Layout>::SLOT_ALIGN);
            assert!(
                size_of::<$slot>() == align_up(size_of::<$t>(), <$t as Std140Layout>::SLOT_ALIGN)
            );
        };
    };
}

macro_rules! layout_scalar4 {
    ($($t:ty),*) => {$(
        layout_impl!($t => 4, padded: $t, slot: Padded16<$t, 12>);
        layout_impl!(Vector2<$t> => 8, padded: Padded8<Vector2<$t>, 0>, slot: Padded16<Vector2<$t>, 8>);
        layout_impl!(Vector3<$t> => 16, padded: Padded16<Vector3<$t>, 4>, slot: Padded16<Vector3<$t>, 4>);
        layout_impl!(Vector4<$t> => 16, padded: Padded16<Vector4<$t>, 0>, slot: Padded16<Vector4<$t>, 0>);
    )*};
}
layout_scalar4!(f32, i32, u32);

layout_impl!(f64 => 8, padded: f64, slot: Padded16<f64, 8>);
layout_impl!(Vector2<f64> => 16, padded: Padded16<Vector2<f64>, 0>, slot: Padded16<Vector2<f64>, 0>);
layout_impl!(Vector3<f64> => 32, padded: Padded32<Vector3<f64>, 8>, slot: Padded32<Vector3<f64>, 8>);
layout_impl!(Vector4<f64> => 32, padded: Padded32<Vector4<f64>, 0>, slot: Padded32<Vector4<f64>, 0>);

// ---- matrices (array of columns; each column padded to its slot) --------------

// SAFETY: an array of column slots, each of which satisfies the contract.
unsafe impl<V: Vector + Std140Layout, const C: usize> Std140Layout for Matrix<V, C> {
    /// The column slot's alignment: 16 for every f32 matrix and dmat2, 32 for
    /// dmat3/dmat4 (dvec4 slots).
    const ALIGN: usize = V::SLOT_ALIGN;
    type Padded = PaddedCols<V::Slot, C>;
    type Slot = PaddedCols<V::Slot, C>;
    type Field = PaddedCols<V::Slot, C>;
}
// SAFETY: as above.
unsafe impl<V: Vector + Std430Layout, const C: usize> Std430Layout for Matrix<V, C> {
    /// The column's natural alignment, not rounded.
    const ALIGN: usize = V::ALIGN;
    type Padded = PaddedCols<V::Padded, C>;
    type Field = PaddedCols<V::Padded, C>;
}

// ---- arrays -------------------------------------------------------------------

// SAFETY: an array of element slots, each of which satisfies the contract.
unsafe impl<T: Std140Layout, const N: usize> Std140Layout for [T; N] {
    /// Arrays align to their element's (rounded) slot.
    const ALIGN: usize = T::SLOT_ALIGN;
    type Padded = [T::Slot; N];
    type Slot = [T::Slot; N];
    type Field = [T::Slot; N];
}
// SAFETY: as above.
unsafe impl<T: Std430Layout, const N: usize> Std430Layout for [T; N] {
    /// Arrays align to their element; no rounding.
    const ALIGN: usize = T::ALIGN;
    type Padded = [T::Padded; N];
    type Field = [T::Padded; N];
}
